import 'package:flutter/material.dart';
import 'package:rayyan_driver/core/theme/app_color_scheme.dart';

/// Blends every colour of [a] towards [b] by [t]; [AppColorScheme.lerp].
AppColorScheme lerpColorScheme(AppColorScheme a, AppColorScheme b, double t) {
  Color mix(Color x, Color y) => Color.lerp(x, y, t) ?? x;
  return AppColorScheme(
    brand: mix(a.brand, b.brand),
    brandElevated: mix(a.brandElevated, b.brandElevated),
    onBrand: mix(a.onBrand, b.onBrand),
    accent: mix(a.accent, b.accent),
    accentSubtle: mix(a.accentSubtle, b.accentSubtle),
    accentTint: mix(a.accentTint, b.accentTint),
    background: mix(a.background, b.background),
    surface: mix(a.surface, b.surface),
    cardBorder: mix(a.cardBorder, b.cardBorder),
    selectedSurface: mix(a.selectedSurface, b.selectedSurface),
    outline: mix(a.outline, b.outline),
    textPrimary: mix(a.textPrimary, b.textPrimary),
    textSecondary: mix(a.textSecondary, b.textSecondary),
    textTertiary: mix(a.textTertiary, b.textTertiary),
    textMuted: mix(a.textMuted, b.textMuted),
    iconPrimary: mix(a.iconPrimary, b.iconPrimary),
    iconSecondary: mix(a.iconSecondary, b.iconSecondary),
    disabled: mix(a.disabled, b.disabled),
    success: mix(a.success, b.success),
    error: mix(a.error, b.error),
    warning: mix(a.warning, b.warning),
    warningSurface: mix(a.warningSurface, b.warningSurface),
    info: mix(a.info, b.info),
    infoSurface: mix(a.infoSurface, b.infoSurface),
    successSurface: mix(a.successSurface, b.successSurface),
    errorSurface: mix(a.errorSurface, b.errorSurface),
    inputBorder: mix(a.inputBorder, b.inputBorder),
    textSubtle: mix(a.textSubtle, b.textSubtle),
    ribbon: mix(a.ribbon, b.ribbon),
    confirmed: mix(a.confirmed, b.confirmed),
    navGlow: mix(a.navGlow, b.navGlow),
    onAccentMuted: mix(a.onAccentMuted, b.onAccentMuted),
    promoVeil: mix(a.promoVeil, b.promoVeil),
    attention: mix(a.attention, b.attention),
    accentStrong: mix(a.accentStrong, b.accentStrong),
    onBrandMuted: mix(a.onBrandMuted, b.onBrandMuted),
    onBrandVeil: mix(a.onBrandVeil, b.onBrandVeil),
    positive: mix(a.positive, b.positive),
    hairline: mix(a.hairline, b.hairline),
    accentWash: mix(a.accentWash, b.accentWash),
    brandDeep: mix(a.brandDeep, b.brandDeep),
    chipFill: mix(a.chipFill, b.chipFill),
    fieldDisabled: mix(a.fieldDisabled, b.fieldDisabled),
    receiptEdge: mix(a.receiptEdge, b.receiptEdge),
    dangerStrong: mix(a.dangerStrong, b.dangerStrong),
    scrim: mix(a.scrim, b.scrim),
    overlayButton: mix(a.overlayButton, b.overlayButton),
    overlayButtonBorder: mix(a.overlayButtonBorder, b.overlayButtonBorder),
  );
}
